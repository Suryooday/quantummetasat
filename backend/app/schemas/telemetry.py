"""Telemetry event models and schemas for live WebSocket streaming."""
from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field
import time

class TelemetryEvent(BaseModel):
    """Structured telemetry event payload."""
    event: str = Field(..., description="Event name identifier")
    timestamp: float = Field(default_factory=time.time, description="Unix timestamp in seconds")
    timestamp_formatted: str = Field(default="", description="Human-readable elapsed timestamp string")
    stage: str = Field(..., description="Current communication pipeline stage")
    step_index: int = Field(default=0, description="Sequential stage step index")
    total_steps: int = Field(default=10, description="Total pipeline steps")
    status: str = Field(default="in_progress", description="Status: 'pending', 'in_progress', 'completed', 'error'")
    is_mock: bool = Field(default=False, description="Whether this event is generated by Demo/Mock mode")
    description: str = Field(default="", description="Detailed human-readable event description")
    inputs: Dict[str, Any] = Field(default_factory=dict, description="Input parameters and mathematical inputs")
    outputs: Dict[str, Any] = Field(default_factory=dict, description="Calculated values, tensors, or telemetry outputs")
    equations: List[str] = Field(default_factory=list, description="Mathematical LaTeX equations associated with this event")
    logs: List[str] = Field(default_factory=list, description="Telemetry logs and calculations")
